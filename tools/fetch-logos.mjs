// Downloads club/team logos from ESPN into logos/ and writes clubs.js.
// Run: node tools/fetch-logos.mjs   (re-run after adding clubs; existing files are kept)
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const { FOOTBALL, BASKETBALL, NBA_TEAMS } = require(path.join(root, "players.js"));

// Search wording where the plain name finds the wrong club.
const QUERY = {
  "Inter Milan": "Internazionale", "AS Roma": "AS Roma", "Nacional": "Nacional Uruguay",
  "Independiente": "Independiente Argentina", "River Plate": "River Plate Argentina",
  "Guangzhou": "Guangzhou", "Al-Ahli": "Al-Ahli Saudi", "Olimpia": "Olimpia Paraguay",
  "Rangers": "Rangers Scotland", "Celtic": "Celtic Scotland", "Qatar SC": "Qatar SC",
  "CF Montréal": "CF Montreal", "Paris Saint-Germain": "Paris Saint-Germain",
  "Metalurh Donetsk": "Metalurh Donetsk", "ATK": "ATK Mohun Bagan", "Den Bosch": "FC Den Bosch",
};
const OVERRIDE = JSON.parse(fs.existsSync(path.join(root, "tools/club-ids.json")) ? fs.readFileSync(path.join(root, "tools/club-ids.json"), "utf8") : "{}");

const slug = s => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function get(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    try { const r = await fetch(url, { signal: AbortSignal.timeout(20000) }); if (r.ok) return r; if (r.status === 404) return null; } catch {}
    await sleep(800);
  }
  return null;
}
async function save(img, file) {
  if (fs.existsSync(file)) return true;
  const r = await get(`https://a.espncdn.com/combiner/i?img=${img}&h=200&w=200`);
  if (!r) return false;
  fs.writeFileSync(file, Buffer.from(await r.arrayBuffer()));
  return true;
}

const out = { football: {}, basketball: {} };
fs.mkdirSync(path.join(root, "logos/fb"), { recursive: true });
fs.mkdirSync(path.join(root, "logos/nba"), { recursive: true });

const clubs = [...new Set(FOOTBALL.flatMap(p => p[3].map(s => s[0])))];
const report = [];
await Promise.all(clubs.map(async (club, i) => {
  await sleep(i * 60);
  let id = OVERRIDE[club], found = club;
  if (id === undefined) {
    const r = await get(`https://site.web.api.espn.com/apis/search/v2?query=${encodeURIComponent(QUERY[club] || club)}&limit=10&type=team`);
    const j = r ? await r.json() : null;
    const teams = (j?.results || []).filter(x => x.type === "team").flatMap(x => x.contents || []).filter(t => t.uid?.startsWith("s:600~"));
    const t = teams[0];
    if (t) { id = t.uid.split("t:")[1]; found = t.displayName + " | " + (t.subtitle || ""); }
  }
  const file = `logos/fb/${slug(club)}.png`;
  const ok = id ? await save(`/i/teamlogos/soccer/500/${id}.png`, path.join(root, file)) : false;
  out.football[club] = ok ? file : null;
  report.push(`${ok ? "ok  " : "MISS"} ${club.padEnd(28)} -> ${id || "-"} ${found}`);
}));

for (const [key, [name, abbr, c1, c2]] of Object.entries(NBA_TEAMS)) {
  const file = `logos/nba/${key.toLowerCase()}.png`;
  const ok = abbr ? await save(`/i/teamlogos/nba/500/${abbr}.png`, path.join(root, file)) : false;
  out.basketball[key] = { name, logo: ok ? file : null, colors: c1 ? [c1, c2] : null };
  if (!ok) report.push(`BADGE ${key} ${name}`);
}

report.sort();
console.log(report.join("\n"));
fs.writeFileSync(path.join(root, "clubs.js"), "// Generated by tools/fetch-logos.mjs\nconst LOGOS = " + JSON.stringify(out, null, 1) + ";\n");
